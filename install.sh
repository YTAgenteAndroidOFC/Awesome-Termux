#!/data/data/com.termux/files/usr/bin/bash
set -Eeuo pipefail
APP_NAME="Awesome Termux"
TERMUX_DIR="$HOME/.termux"
BACKUP_DIR="$HOME/.awesome-termux-backups"
COLORS_FILE="$TERMUX_DIR/colors.properties"
FONT_FILE="$TERMUX_DIR/font.ttf"
mkdir -p "$TERMUX_DIR" "$BACKUP_DIR"

backup() {
  local stamp dest
  stamp="$(date +%Y%m%d-%H%M%S)"
  dest="$BACKUP_DIR/$stamp"
  mkdir -p "$dest"
  [[ -f "$COLORS_FILE" ]] && cp -p "$COLORS_FILE" "$dest/colors.properties" || true
  [[ -f "$FONT_FILE" ]] && cp -p "$FONT_FILE" "$dest/font.ttf" || true
  echo "Backup salvo em: $dest"
}
reload_settings() {
  command -v termux-reload-settings >/dev/null 2>&1 && termux-reload-settings || echo "Feche e reabra o Termux para recarregar."
}
write_colors() {
  local bg="$1" fg="$2" cursor="$3"
  backup
  cat > "$COLORS_FILE" <<EOF
# Generated by Awesome Termux
background=$bg
foreground=$fg
cursor=$cursor
EOF
  reload_settings
  echo "Cores aplicadas."
}
valid_hex() { [[ "$1" =~ ^#?[0-9A-Fa-f]{6}$ ]]; }
normalize_hex() { local v="${1#\#}"; printf '#%s' "${v^^}"; }

choose_preset() {
  echo "1) AMOLED  #000000"
  echo "2) Purple Dark  #0F0B12"
  echo "3) Android Green  #07140B"
  echo "4) Dracula  #282A36"
  echo "5) Nord  #2E3440"
  read -rp "Escolha: " choice
  case "$choice" in
    1) write_colors "#000000" "#E6E6E6" "#FFFFFF" ;;
    2) write_colors "#0F0B12" "#E6E1E9" "#BB86FC" ;;
    3) write_colors "#07140B" "#E8F5E9" "#00C853" ;;
    4) write_colors "#282A36" "#F8F8F2" "#BD93F9" ;;
    5) write_colors "#2E3440" "#D8DEE9" "#88C0D0" ;;
    *) echo "Opção inválida." ;;
  esac
}
custom_colors() {
  local bg fg cursor
  read -rp "Fundo (#RRGGBB): " bg
  read -rp "Texto (#RRGGBB): " fg
  read -rp "Cursor (#RRGGBB): " cursor
  if ! valid_hex "$bg" || ! valid_hex "$fg" || ! valid_hex "$cursor"; then
    echo "HEX inválido. Use seis dígitos, por exemplo #0F0B12."
    return 1
  fi
  write_colors "$(normalize_hex "$bg")" "$(normalize_hex "$fg")" "$(normalize_hex "$cursor")"
}
install_font_url() {
  local url tmp
  read -rp "URL direta HTTPS do arquivo de fonte: " url
  [[ "$url" == https://* ]] || { echo "Use uma URL HTTPS."; return 1; }
  tmp="$(mktemp)"
  if ! curl -fL --retry 2 "$url" -o "$tmp"; then rm -f "$tmp"; echo "Falha no download."; return 1; fi
  if [[ ! -s "$tmp" ]] || ! file "$tmp" | grep -qiE 'TrueType|OpenType|font'; then
    rm -f "$tmp"; echo "O arquivo não parece ser uma fonte válida."; return 1
  fi
  backup
  install -m 0644 "$tmp" "$FONT_FILE"
  rm -f "$tmp"
  reload_settings
  echo "Fonte instalada em $FONT_FILE"
}
install_font_local() {
  local src
  read -rp "Caminho completo do arquivo .ttf/.otf: " src
  [[ -f "$src" ]] || { echo "Arquivo não encontrado."; return 1; }
  file "$src" | grep -qiE 'TrueType|OpenType|font' || { echo "O arquivo não parece ser uma fonte."; return 1; }
  backup
  install -m 0644 "$src" "$FONT_FILE"
  reload_settings
  echo "Fonte instalada em $FONT_FILE"
}
restore_backup() {
  local latest
  latest="$(find "$BACKUP_DIR" -mindepth 1 -maxdepth 1 -type d | sort | tail -n 1)"
  [[ -n "$latest" ]] || { echo "Nenhum backup encontrado."; return 1; }
  [[ -f "$latest/colors.properties" ]] && cp -p "$latest/colors.properties" "$COLORS_FILE" || true
  [[ -f "$latest/font.ttf" ]] && cp -p "$latest/font.ttf" "$FONT_FILE" || true
  reload_settings
  echo "Backup restaurado: $latest"
}
while true; do
  echo
  echo "===== $APP_NAME ====="
  echo "1) Presets de cores"
  echo "2) Cor personalizada"
  echo "3) Instalar fonte por URL"
  echo "4) Instalar fonte do armazenamento"
  echo "5) Fazer backup"
  echo "6) Restaurar último backup"
  echo "0) Sair"
  read -rp "Selecione: " opt
  case "$opt" in
    1) choose_preset ;;
    2) custom_colors ;;
    3) install_font_url ;;
    4) install_font_local ;;
    5) backup ;;
    6) restore_backup ;;
    0) exit 0 ;;
    *) echo "Opção inválida." ;;
  esac
done
